#!/usr/bin/env python3
"""Regenerate the demo's assembly data from data.py; leave numeric IDs intact."""
from pathlib import Path
import re
import textwrap
from data import DOGS, MOVES, species_label, sprite_filename

ROOT = Path(__file__).resolve().parents[2]

def replace(path, pattern, replacement, count=1):
    p = ROOT / path
    value, n = re.subn(pattern, replacement, p.read_text(), count=count, flags=re.M)
    if n != count:
        raise ValueError(f"{path}: expected {count} matches, got {n}: {pattern}")
    p.write_text(value)

def block(path, label, replacement):
    replace(path, rf"^{label}:{{1,2}}\n[\s\S]*?(?=^[A-Za-z_]\w*:|\Z)", replacement)

for alias, (slot, name, effect, power, kind, accuracy, pp) in MOVES.items():
    # Index into the existing names table by the constant's original position.
    constants = (ROOT / "constants/move_constants.asm").read_text()
    order = re.findall(r"^\s*const (\w+)\s*;", constants, re.M)
    index = order.index(slot)-1 # NO_MOVE is not in MoveNames
    p = ROOT / "data/moves/names.asm"
    lines = p.read_text().splitlines(keepends=True)
    line_index = [i for i, line in enumerate(lines) if line.startswith('\tli "')][index]
    lines[line_index] = f'\tli "{name}"\n'
    p.write_text(''.join(lines))
    replace("data/moves/moves.asm", rf"^\tmove {slot},[^\n]*", f"\tmove {slot}, {effect}, {power}, {kind}, {accuracy}, {pp}")

aliases = ["; Dog display names use existing species and move IDs."]
for d in DOGS:
    aliases.append(f"DEF {d['name']} EQU {d['slot']}")
for alias, values in MOVES.items():
    aliases.append(f"DEF {alias} EQU {values[0]}")
(ROOT / "constants/dog_constants.asm").write_text('\n'.join(aliases)+'\n')
p = ROOT / "includes.asm"
if 'INCLUDE "constants/dog_constants.asm"' not in p.read_text():
    p.write_text(p.read_text().replace('INCLUDE "constants/pokedex_constants.asm"', 'INCLUDE "constants/dog_constants.asm"\nINCLUDE "constants/pokedex_constants.asm"'))

for d in DOGS:
    slot, name = d['slot'], d['name']
    lower, label = sprite_filename(slot), species_label(slot)
    # Names table uses internal IDs, icons use Pokédex order.
    constants = (ROOT / "constants/pokemon_constants.asm").read_text()
    # There are unused internal species IDs, so use the explicit hexadecimal ID.
    index = int(re.search(rf"^\s*const {slot}\s*; \$([0-9A-F]+)", constants, re.M)[1], 16)-1
    p = ROOT / "data/pokemon/names.asm"
    lines = p.read_text().splitlines(keepends=True)
    line_index = [i for i, line in enumerate(lines) if line.startswith('\tdname "')][index]
    lines[line_index] = f'\tdname "{name}"\n'
    p.write_text(''.join(lines))
    stats = ', '.join(map(str, d['stats']))
    moves = ', '.join(d['base'] + ('NO_MOVE',)*(4-len(d['base'])))
    data = f'''; Generated by tools/dogs/generate_data.py: {name} / {d['breed']}
\tdb DEX_{slot}
\tdb {stats} ; hp, atk, def, spd, spc
\tdb {', '.join(d['types'])}
\tdb {d['catch']}
\tdb {d['exp']}
\tINCBIN "gfx/pokemon/front/{lower}.pic", 0, 1
\tdw {label}PicFront, {label}PicBack
\tdb {moves}
\tdb GROWTH_MEDIUM_SLOW
\ttmhm {', '.join(d['tms'])}
\tdb 0
'''
    (ROOT / f"data/pokemon/base_stats/{slot.lower().replace('_', '')}.asm").write_text(data)
    evos = f"\tdb EVOLVE_LEVEL, {d['evolution'][0]}, {d['evolution'][1]}\n" if d['evolution'] else ''
    for branch in d.get('branch_evolutions', []):
        assert branch['method'] == 'stone'
        evos += f"\tdb EVOLVE_ITEM, {branch['item']}, 1, {branch['target']}\n"
    learns = ''.join(f"\tdb {level}, {move}\n" for level, move in d['learnset'])
    block("data/pokemon/evos_moves.asm", label+"EvosMoves", f"{label}EvosMoves:\n; {name}: same breed, growing maturity.\n{evos}\tdb 0\n{learns}\tdb 0\n\n")
    block("data/pokemon/dex_entries.asm", label+"DexEntry", f'''{label}DexEntry:
\tdb "{d['category']}@"
\tdb {d['height'][0]},{d['height'][1]}
\tdw {d['weight']}
\ttext_far _{label}DexEntry
\ttext_end

''')
    descriptors = {
        'GROENENDAEL': ('A leaf-coated dog', 'guards its pack.', 'Its keen hearing', 'finds lost friends', 'in the tall grass.'),
        'SHIBA INU': ('Its curled tail', 'glows with embers.', 'This bold partner', 'leaps through heat', 'to help its pack.'),
        'NEWFOUNDLAND': ('A strong swimmer', 'with a wave coat.', 'It carries tired', 'friends to safety', 'across deep water.'),
        'BEAGLE': ('Its clever nose', 'finds lost trails.', 'It follows scents', 'and calls its pack', 'with a happy howl.'),
        'PAPILLON': ('Its silky ears', 'flutter like wings', 'It scatters pollen', 'as it dances over', 'forest flowers.'),
        'BOXER': ('It trains its paws', 'in playful spars.', 'Its quick footwork', 'helps its friends', 'stand up to rocks.'),
        'BULLDOG': ('Its stone coat', 'protects its pack.', 'It plants its paws', 'and holds the line', 'against its foes.'),
        'MASTIFF': ('A mighty guardian', 'with a stone mane.', 'Its booming howl', 'echoes through the', 'hills of PEWTER.'),
        'YORKSHIRE TERRIER': ('Its silky coat', 'hides tiny barbs.', 'It scouts ahead', 'and calls the pack', 'with sharp yips.'),
        'WHIPPET': ('Its swift paws', 'ride on the wind.', 'It races ahead', 'to guide friends', 'along safe trails.'),
        'GREYHOUND': ('Its long legs', 'outrun the breeze.', 'It circles its', 'pack to keep every', 'friend together.'),
        'DACHSHUND': ('Its low body', 'slips into dens.', 'It marks a trail', 'with venom scents', 'to warn its pack.'),
        'POMERANIAN': ('Its fluffy coat', 'crackles with sparks', 'It lights a path', 'for friends with', 'an electric yip.'),
        'JACK RUSSELL TERRIER': ('Its nimble paws', 'dig narrow tunnels', 'It searches the', 'ground for hidden', 'treasures to share'),
        'COCKER SPANIEL': ('Its soft ears', 'muffle loud sounds', 'Its soothing howl', 'helps tired friends', 'settle down to nap'),
        'ITALIAN GREYHOUND': ('Its slender paws', 'skim the cave floor', 'It follows echoes', 'through dark halls', 'to find lost pups.'),
        'LAGOTTO ROMAGNOLO': ('Its curly coat', 'hides leafy tufts.', 'It finds truffles', 'and shares them', 'with hungry pups.'),
        'POODLE': ('Its clever mind', 'solves pack puzzles', 'It reads a friend', 'with a quiet gaze', 'and a gentle bark'),
        'OTTERHOUND': ('Its shaggy coat', 'keeps water away.', 'It follows river', 'scents to rescue', 'friends in trouble'),
        'ENGLISH SPRINGER SPANIEL': ('Its springy paws', 'splash over streams', 'It fetches lost', 'items from water', 'with a happy bark'),
    }
    breed_lines = textwrap.wrap(d['breed']+'.', 18, break_long_words=False)
    prose = ' '.join(descriptors[d['breed']]) if d['breed'] in descriptors else d['dex_description'].removeprefix(d['breed']+' ').removeprefix(d['breed']+'. ')
    lines = breed_lines + textwrap.wrap(prose, 18, break_long_words=False)
    assert all(len(line) <= 18 for line in lines), lines
    text = f'_{label}DexEntry::\n'
    for index, line in enumerate(lines):
        command = 'text' if index == 0 else 'page' if index % 3 == 0 else 'next'
        text += f'\t{command} "{line}"\n'
    text += '\tdex\n\n'
    block("data/pokemon/dex_text.asm", '_'+label+"DexEntry", text)
    replace("data/pokemon/menu_icons.asm", rf"^\tnybble \w+(\s*; {label})$", rf"\tnybble ICON_QUADRUPED\1")

for filename in ('evos_moves.asm', 'dex_text.asm', 'dex_entries.asm'):
    path = ROOT / 'data/pokemon' / filename
    path.write_text(path.read_text().rstrip()+'\n')

# HM menu names have a separate table and an explicit left-edge coordinate.
for alias in ('BRAMBLE_BITE','SKYBOUND','DOG_PADDLE','HAUL','BEACON_BARK','BURROW_RUSH','HOMEBOUND','RESCUE_REST'):
    slot, name, *_ = MOVES[alias]
    # Replace by row number, making regeneration independent of previous names.
    index = ['CUT','FLY','UNUSED','SURF','STRENGTH','FLASH','DIG','TELEPORT','SOFTBOILED'].index(slot)
    p = ROOT / 'data/moves/field_move_names.asm'
    lines = p.read_text().splitlines(keepends=True)
    positions = [i for i, line in enumerate(lines) if line.startswith('\tdb "')]
    lines[positions[index]] = f'\tdb "{name}@"\n'
    p.write_text(''.join(lines))
    replace('data/moves/field_moves.asm', rf"^(\tdb {slot},\s*\d+, )\$[0-9A-F]+", rf"\g<1>${min(12,18-len(name)):02X}")

print(f"Generated {len(DOGS)} dog forms and {len(MOVES)} dog moves.")
